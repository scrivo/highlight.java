'use strict';

/**
 * Copies the highlight.js stylesheets into the resources of highlight.java and
 * writes an index of the themes with their background colors.
 *
 * usage: node styles.js <highlight.js dir>
 */

const fs = require('fs');
const path = require('path');

const NAMED_COLORS = {
    white: [255, 255, 255],
    black: [0, 0, 0],
    silver: [192, 192, 192],
    gray: [128, 128, 128],
    grey: [128, 128, 128],
    navy: [0, 0, 128],
};

/** The background color of the `.hljs` rule, white by default. */
function backgroundColor(css) {
    css = css.replace(/\/\*[\s\S]*?\*\//g, '');
    let color = [255, 255, 255];
    const ruleRe = /([^{}]+)\{([^}]*)\}/g;
    let rule;
    while ((rule = ruleRe.exec(css)) !== null) {
        const selectors = rule[1].split(',').map(function (s) { return s.trim(); });
        if (!selectors.includes('.hljs')) continue;
        const declarations = {};
        rule[2].split(';').forEach(function (d) {
            const i = d.indexOf(':');
            if (i > 0) declarations[d.slice(0, i).trim().toLowerCase()] = d.slice(i + 1).trim();
        });
        const value = declarations.background || declarations['background-color'];
        const parsed = value && parseColor(value);
        if (parsed) color = parsed;
    }

    return color;
}

function parseColor(value) {
    let m = /#([0-9a-f]{6}|[0-9a-f]{3})\b/i.exec(value);
    if (m) {
        const hex = m[1].length === 3 ? m[1].replace(/./g, '$&$&') : m[1];

        return [0, 2, 4].map(function (i) { return parseInt(hex.slice(i, i + 2), 16); });
    }
    m = /rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)/i.exec(value);
    if (m) return [Number(m[1]), Number(m[2]), Number(m[3])];
    for (const word of value.toLowerCase().split(/\s+/)) {
        if (NAMED_COLORS[word]) return NAMED_COLORS[word];
    }

    return null;
}

module.exports = { backgroundColor: backgroundColor };

if (require.main === module) {
    const hljsDir = process.argv[2];
    if (!hljsDir) {
        console.error('usage: node styles.js <highlight.js dir>');
        process.exit(1);
    }
    const srcDir = path.join(hljsDir, 'src', 'styles');
    const outDir = path.join(__dirname, '..', 'src', 'main', 'resources', 'org', 'scrivo', 'highlight', 'styles');
    fs.rmSync(outDir, { recursive: true, force: true });
    fs.mkdirSync(outDir, { recursive: true });

    const index = ['# Generated by tools/styles.js: the themes and their background colors (r,g,b).'];
    fs.readdirSync(srcDir).sort().forEach(function (file) {
        fs.copyFileSync(path.join(srcDir, file), path.join(outDir, file));
        if (file.endsWith('.css')) {
            const color = backgroundColor(fs.readFileSync(path.join(srcDir, file), 'utf8'));
            index.push(file.slice(0, -4) + '=' + color.join(','));
        }
    });
    fs.writeFileSync(path.join(outDir, 'themes.properties'), index.join('\n') + '\n');
    console.log('Copied ' + (index.length - 1) + ' themes');
}
