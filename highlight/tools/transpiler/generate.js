'use strict';

/**
 * Generates the Java language classes from a highlight.js checkout.
 *
 * usage: node generate.js <highlight.js dir> [language...]
 */

const fs = require('fs');
const path = require('path');
const { transpile, className } = require('./transpile');
const { createHljs } = require('./hljs-env');

const hljsDir = process.argv[2];
if (!hljsDir) {
    console.error('usage: node generate.js <highlight.js dir> [language...]');
    process.exit(1);
}

const langDir = path.join(hljsDir, 'src', 'languages');
const outDir = path.join(__dirname, '..', '..', 'src', 'main', 'java', 'org', 'scrivo', 'highlight', 'languages');
const hljsVersion = JSON.parse(fs.readFileSync(path.join(hljsDir, 'package.json'), 'utf8')).version;

const all = fs.readdirSync(langDir).filter(function (f) { return f.endsWith('.js'); })
    .map(function (f) { return f.slice(0, -3); }).sort();
const selected = process.argv.length > 3 ? process.argv.slice(3) : all;

const env = createHljs(hljsDir);

fs.mkdirSync(outDir, { recursive: true });

let failures = 0;
selected.forEach(function (id) {
    const source = fs.readFileSync(path.join(langDir, id + '.js'), 'utf8');
    try {
        const java = transpile(source, id);
        fs.writeFileSync(path.join(outDir, className(id) + '.java'), java);
    } catch (e) {
        failures++;
        console.error(id + ': ' + e.message);
        if (process.env.DEBUG) console.error(e.stack);
    }
});

function javaString(s) {
    return '"' + s.replace(/[\\"]/g, '\\$&') + '"';
}

// The registry maps language ids to classes, so languages can be listed and
// loaded without scanning the class path.
const registry = [
    '/* This file is generated by tools/transpiler from highlight.js. */',
    '',
    'package org.scrivo.highlight.languages;',
    '',
    'import java.util.Collections;',
    'import java.util.LinkedHashMap;',
    'import java.util.List;',
    'import java.util.Map;',
    'import java.util.function.Supplier;',
    '',
    'import org.scrivo.highlight.LanguageDefinition;',
    '',
    '/**',
    ' * The languages bundled with highlight.java.',
    ' */',
    'public final class Registry {',
    '',
    '\tpublic static final String HIGHLIGHT_JS_VERSION = ' + javaString(hljsVersion) + ';',
    '',
    '\t/** The language ids mapped to their definitions. */',
    '\tpublic static final Map<String, Supplier<LanguageDefinition>> LANGUAGES;',
    '',
    '\t/** The aliases of each language, so languages can be registered without evaluating their definitions. */',
    '\tpublic static final Map<String, List<String>> ALIASES;',
    '',
    '\tprivate static final Map<String, Class<? extends LanguageDefinition>> CLASSES;',
    '',
    '\tstatic {',
    '\t\tMap<String, Supplier<LanguageDefinition>> languages = new LinkedHashMap<>();',
    '\t\tMap<String, List<String>> aliases = new LinkedHashMap<>();',
    '\t\tMap<String, Class<? extends LanguageDefinition>> classes = new LinkedHashMap<>();',
].concat(all.map(function (id) {
    const aliases = env.define(id).aliases || [];
    const cls = className(id);

    return '\t\tadd(languages, aliases, classes, ' + javaString(id) + ', ' + cls + '.class, ' + cls + '::new' +
        (aliases.length ? ', ' + aliases.map(javaString).join(', ') : '') + ');';
})).concat([
    '\t\tLANGUAGES = Collections.unmodifiableMap(languages);',
    '\t\tALIASES = Collections.unmodifiableMap(aliases);',
    '\t\tCLASSES = classes;',
    '\t}',
    '',
    '\tprivate Registry() {',
    '\t}',
    '',
    '\t/** Whether the definition is the one bundled for the language. */',
    '\tpublic static boolean isBundled(String id, LanguageDefinition definition) {',
    '\t\treturn definition != null && CLASSES.get(id) == definition.getClass();',
    '\t}',
    '',
    '\tprivate static void add(Map<String, Supplier<LanguageDefinition>> languages, Map<String, List<String>> aliases,',
    '\t\t\tMap<String, Class<? extends LanguageDefinition>> classes, String id,',
    '\t\t\tClass<? extends LanguageDefinition> type, Supplier<LanguageDefinition> supplier, String... languageAliases) {',
    '\t\tlanguages.put(id, supplier);',
    '\t\taliases.put(id, List.of(languageAliases));',
    '\t\tclasses.put(id, type);',
    '\t}',
    '}',
    '',
]).join('\n');
fs.writeFileSync(path.join(outDir, 'Registry.java'), registry);

console.log('Generated ' + (selected.length - failures) + ' of ' + selected.length + ' languages for highlight.js ' + hljsVersion);
process.exit(failures ? 1 : 0);
